ALTER SESSION SET CURRENT_SCHEMA = system;

CREATE TABLE system.Students (
    student_id VARCHAR2(20) PRIMARY KEY,
    year_enrolled NUMBER,
    student_number NUMBER,
    campus_code VARCHAR2(10),
    course_code VARCHAR2(10),
    year_level NUMBER,
    section CHAR(1),
    status VARCHAR2(20)
);

CREATE TABLE system.Professors (
    professor_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(255)
);

CREATE TABLE system.Subjects (
    subject_code VARCHAR2(20) PRIMARY KEY,
    subject_name VARCHAR2(255)
);

CREATE TABLE system.Classes (
    class_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_code VARCHAR2(20),
    professor_id NUMBER,
    section VARCHAR2(20),
    school_year VARCHAR2(20),
    CONSTRAINT fk_class_subject FOREIGN KEY (subject_code)
        REFERENCES system.Subjects(subject_code),
    CONSTRAINT fk_class_prof FOREIGN KEY (professor_id)
        REFERENCES system.Professors(professor_id)
);

CREATE TABLE system.Evaluations (
    evaluation_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id VARCHAR2(20),
    professor_id NUMBER,
    class_id NUMBER,
    date_submitted TIMESTAMP DEFAULT SYSTIMESTAMP,
    total_score NUMBER,

    CONSTRAINT fk_eval_student FOREIGN KEY (student_id)
        REFERENCES system.Students(student_id),

    CONSTRAINT fk_eval_prof FOREIGN KEY (professor_id)
        REFERENCES system.Professors(professor_id),

    CONSTRAINT fk_eval_class FOREIGN KEY (class_id)
        REFERENCES system.Classes(class_id)
);


CREATE TABLE system.Responses (
    response_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_id NUMBER,
    question_id NUMBER,
    rating NUMBER(1),

    CONSTRAINT fk_resp_eval FOREIGN KEY (evaluation_id)
        REFERENCES system.Evaluations(evaluation_id),

    CONSTRAINT fk_resp_question FOREIGN KEY (question_id)
        REFERENCES system.Questions(question_id)
);

CREATE TABLE system.Remarks (
    remark_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_id NUMBER UNIQUE,
    remarks_text CLOB,

    CONSTRAINT fk_rem_eval FOREIGN KEY (evaluation_id)
        REFERENCES system.Evaluations(evaluation_id)
);

CREATE TABLE system.Forms (
    form_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_name VARCHAR2(255),
    is_remarks NUMBER(1)
);

CREATE TABLE system.Categories (
    category_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_id NUMBER,
    category_name VARCHAR2(255),

    CONSTRAINT fk_cat_form FOREIGN KEY (form_id)
        REFERENCES system.Forms(form_id)
);

CREATE TABLE system.Questions (
    question_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id NUMBER,
    question_text VARCHAR2(500),

    CONSTRAINT fk_q_cat FOREIGN KEY (category_id)
        REFERENCES system.Categories(category_id)
);

