-- FUNCTION 1: Count responses for an evaluation
CREATE OR REPLACE FUNCTION count_responses(p_eval_id NUMBER)
RETURN NUMBER
AS
    v_total NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO v_total
    FROM Responses
    WHERE evaluation_id = p_eval_id;

    RETURN v_total;
END;
/

-- FUNCTION 2: Get remarks text for an evaluation
CREATE OR REPLACE FUNCTION get_remarks(p_eval_id NUMBER)
RETURN VARCHAR2
AS
    v_text VARCHAR2(4000);
BEGIN
    SELECT remarks_text
    INTO v_text
    FROM Remarks
    WHERE evaluation_id = p_eval_id;

    RETURN v_text;
END;
/

-- FUNCTION 3: Check if enrollment has been evaluated
CREATE OR REPLACE FUNCTION is_evaluated(p_enrollment_id NUMBER)
RETURN NUMBER
AS
    v_count NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO v_count
    FROM Evaluations
    WHERE enrollment_id = p_enrollment_id
      AND status = 'SUBMITTED';

    IF v_count > 0 THEN
        RETURN 1;
    ELSE
        RETURN 0;
    END IF;
END;
/

-- FUNCTION 4: Get professor's average rating
CREATE OR REPLACE FUNCTION get_avg_rating(p_prof_id NUMBER)
RETURN NUMBER
AS
    v_avg NUMBER;
BEGIN
    SELECT ROUND(AVG(r.rating), 2)
    INTO v_avg
    FROM Professors p
    JOIN Classes c ON p.professor_id = c.professor_id
    JOIN Enrollments e ON c.class_id = e.class_id
    JOIN Evaluations ev ON e.enrollment_id = ev.enrollment_id
    JOIN Responses r ON ev.evaluation_id = r.evaluation_id
    WHERE p.professor_id = p_prof_id
      AND ev.status = 'SUBMITTED';

    RETURN NVL(v_avg, 0);
END;
/

-- FUNCTION 5: Count enrollments for a student
CREATE OR REPLACE FUNCTION count_enrollments(p_student_id VARCHAR2)
RETURN NUMBER
AS
    v_count NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO v_count
    FROM Enrollments
    WHERE student_id = p_student_id
      AND status = 'ACTIVE';

    RETURN v_count;
END;
/

-- FUNCTION 6: Get completion percentage for an evaluation
CREATE OR REPLACE FUNCTION get_completion_percentage(p_evaluation_id NUMBER)
RETURN NUMBER
AS
    v_total_questions NUMBER;
    v_answered NUMBER;
    v_percentage NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_total_questions
    FROM Questions q
    JOIN Categories cat ON q.category_id = cat.category_id
    JOIN Forms f ON cat.form_id = f.form_id
    WHERE f.form_name = 'Student Evaluation Form'
      AND q.is_active = 1;
    
    SELECT COUNT(*) INTO v_answered
    FROM Responses
    WHERE evaluation_id = p_evaluation_id;
    
    IF v_total_questions > 0 THEN
        v_percentage := ROUND((v_answered / v_total_questions) * 100, 2);
    ELSE
        v_percentage := 0;
    END IF;
    
    RETURN v_percentage;
END;
/

-- FUNCTION 7: Get category average rating for a professor
CREATE OR REPLACE FUNCTION get_category_avg_rating(
    p_prof_id NUMBER, 
    p_category_name VARCHAR2
)
RETURN NUMBER
AS
    v_avg NUMBER;
BEGIN
    SELECT ROUND(AVG(r.rating), 2)
    INTO v_avg
    FROM Responses r
    JOIN Evaluations ev ON r.evaluation_id = ev.evaluation_id
    JOIN Enrollments e ON ev.enrollment_id = e.enrollment_id
    JOIN Classes c ON e.class_id = c.class_id
    JOIN Professors p ON c.professor_id = p.professor_id
    JOIN Questions q ON r.question_id = q.question_id
    JOIN Categories cat ON q.category_id = cat.category_id
    WHERE p.professor_id = p_prof_id
      AND cat.category_name = p_category_name
      AND ev.status = 'SUBMITTED';
    
    RETURN NVL(v_avg, 0);
END;
/

-- FUNCTION 8: Get professor's total number of evaluations
CREATE OR REPLACE FUNCTION get_total_evaluations(p_prof_id NUMBER)
RETURN NUMBER
AS
    v_count NUMBER;
BEGIN
    SELECT COUNT(DISTINCT ev.evaluation_id)
    INTO v_count
    FROM Evaluations ev
    JOIN Enrollments e ON ev.enrollment_id = e.enrollment_id
    JOIN Classes c ON e.class_id = c.class_id
    WHERE c.professor_id = p_prof_id
      AND ev.status = 'SUBMITTED';
    
    RETURN v_count;
END;
/

-- FUNCTION 9: Check if student has completed all evaluations
CREATE OR REPLACE FUNCTION has_completed_all_evaluations(p_student_id VARCHAR2)
RETURN VARCHAR2
AS
    v_total_classes NUMBER;
    v_completed NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_total_classes
    FROM Enrollments
    WHERE student_id = p_student_id
      AND status = 'ACTIVE';
    
    SELECT COUNT(*) INTO v_completed
    FROM Enrollments e
    JOIN Evaluations ev ON e.enrollment_id = ev.enrollment_id
    WHERE e.student_id = p_student_id
      AND e.status = 'ACTIVE'
      AND ev.status = 'SUBMITTED';
    
    IF v_total_classes = 0 THEN
        RETURN 'NO ENROLLMENTS';
    ELSIF v_total_classes = v_completed THEN
        RETURN 'COMPLETED';
    ELSE
        RETURN 'INCOMPLETE (' || v_completed || '/' || v_total_classes || ')';
    END IF;
END;
/

-- FUNCTION 10: Get rating distribution for a professor
CREATE OR REPLACE FUNCTION get_rating_distribution(
    p_prof_id NUMBER,
    p_rating NUMBER
)
RETURN NUMBER
AS
    v_count NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO v_count
    FROM Responses r
    JOIN Evaluations ev ON r.evaluation_id = ev.evaluation_id
    JOIN Enrollments e ON ev.enrollment_id = e.enrollment_id
    JOIN Classes c ON e.class_id = c.class_id
    WHERE c.professor_id = p_prof_id
      AND r.rating = p_rating
      AND ev.status = 'SUBMITTED';
    
    RETURN v_count;
END;
/

-- FUNCTION 11: Get student's latest evaluation date
CREATE OR REPLACE FUNCTION get_latest_evaluation_date(p_student_id VARCHAR2)
RETURN TIMESTAMP
AS
    v_date TIMESTAMP;
BEGIN
    SELECT MAX(ev.date_submitted)
    INTO v_date
    FROM Evaluations ev
    JOIN Enrollments e ON ev.enrollment_id = e.enrollment_id
    WHERE e.student_id = p_student_id
      AND ev.status = 'SUBMITTED';
    
    RETURN v_date;
END;
/

-- FUNCTION 12: NEW - Get class occupancy rate
CREATE OR REPLACE FUNCTION get_class_occupancy(p_class_id NUMBER)
RETURN NUMBER
AS
    v_current NUMBER;
    v_max NUMBER;
    v_rate NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_current
    FROM Enrollments
    WHERE class_id = p_class_id AND status = 'ACTIVE';
    
    SELECT max_students INTO v_max
    FROM Classes
    WHERE class_id = p_class_id;
    
    IF v_max > 0 THEN
        v_rate := ROUND((v_current / v_max) * 100, 2);
    ELSE
        v_rate := 0;
    END IF;
    
    RETURN v_rate;
END;
/

-- FUNCTION 13: NEW - Get student's GPA based on evaluations
CREATE OR REPLACE FUNCTION get_student_evaluation_gpa(p_student_id VARCHAR2)
RETURN NUMBER
AS
    v_gpa NUMBER;
BEGIN
    SELECT ROUND(AVG(r.rating), 2)
    INTO v_gpa
    FROM Responses r
    JOIN Evaluations ev ON r.evaluation_id = ev.evaluation_id
    JOIN Enrollments e ON ev.enrollment_id = e.enrollment_id
    WHERE e.student_id = p_student_id
      AND ev.status = 'SUBMITTED';
    
    RETURN NVL(v_gpa, 0);
END;
/

