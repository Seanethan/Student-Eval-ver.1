-- STUDENTS
CREATE TABLE Students (
    student_id VARCHAR2(20) PRIMARY KEY,
    course_code VARCHAR2(20),
    year_level NUMBER(1),
    section CHAR(1)
);

-- PROFESSORS
CREATE TABLE Professors (
    professor_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(255) NOT NULL
);

-- SUBJECTS
CREATE TABLE Subjects (
    subject_code VARCHAR2(20) PRIMARY KEY,
    subject_name VARCHAR2(255) NOT NULL
);

-- CLASSES
CREATE TABLE Classes (
    class_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_code VARCHAR2(20),
    professor_id NUMBER,
    section VARCHAR2(20),
    school_year VARCHAR2(20),

    CONSTRAINT fk_class_subject FOREIGN KEY (subject_code)
        REFERENCES Subjects(subject_code),

    CONSTRAINT fk_class_prof FOREIGN KEY (professor_id)
        REFERENCES Professors(professor_id)
);

-- ENROLLMENTS
CREATE TABLE Enrollments (
    enrollment_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id VARCHAR2(20),
    class_id NUMBER,

    CONSTRAINT fk_enroll_student FOREIGN KEY (student_id)
        REFERENCES Students(student_id),

    CONSTRAINT fk_enroll_class FOREIGN KEY (class_id)
        REFERENCES Classes(class_id)
);

-- EVALUATIONS
CREATE TABLE Evaluations (
    evaluation_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrollment_id NUMBER UNIQUE,
    date_submitted TIMESTAMP DEFAULT SYSTIMESTAMP,

    CONSTRAINT fk_eval_enroll FOREIGN KEY (enrollment_id)
        REFERENCES Enrollments(enrollment_id)
);

-- FORMS
CREATE TABLE Forms (
    form_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_name VARCHAR2(255)
);

-- CATEGORIES
CREATE TABLE Categories (
    category_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_id NUMBER,
    category_name VARCHAR2(255),

    CONSTRAINT fk_cat_form FOREIGN KEY (form_id)
        REFERENCES Forms(form_id)
);

-- QUESTIONS
CREATE TABLE Questions (
    question_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id NUMBER,
    question_text VARCHAR2(500),

    CONSTRAINT fk_q_cat FOREIGN KEY (category_id)
        REFERENCES Categories(category_id)
);

-- RESPONSES
CREATE TABLE Responses (
    response_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_id NUMBER,
    question_id NUMBER,
    rating NUMBER(1),

    CONSTRAINT fk_resp_eval FOREIGN KEY (evaluation_id)
        REFERENCES Evaluations(evaluation_id),

    CONSTRAINT fk_resp_question FOREIGN KEY (question_id)
        REFERENCES Questions(question_id),

    CONSTRAINT chk_rating CHECK (rating BETWEEN 1 AND 5)
);

-- REMARKS
CREATE TABLE Remarks (
    evaluation_id NUMBER PRIMARY KEY,
    remarks_text CLOB,

    CONSTRAINT fk_rem_eval FOREIGN KEY (evaluation_id)
        REFERENCES Evaluations(evaluation_id)
);


