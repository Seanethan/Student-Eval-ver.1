-- =========================
-- 1. STUDENTS
-- =========================
CREATE TABLE Students (
    student_id VARCHAR2(20) PRIMARY KEY,
    year_enrolled NUMBER,
    student_number NUMBER,
    campus_code VARCHAR2(10),
    course_code VARCHAR2(10),
    year_level NUMBER,
    section CHAR(1),
    status VARCHAR2(20)
);

-- =========================
-- 2. PROFESSORS
-- =========================
CREATE TABLE Professors (
    professor_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(255)
);

-- =========================
-- 3. SUBJECTS
-- =========================
CREATE TABLE Subjects (
    subject_code VARCHAR2(20) PRIMARY KEY,
    subject_name VARCHAR2(255)
);

-- =========================
-- 4. CLASSES
-- =========================
CREATE TABLE Classes (
    class_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_code VARCHAR2(20),
    professor_id NUMBER,
    section VARCHAR2(20),
    school_year VARCHAR2(20),
    CONSTRAINT fk_classes_subject FOREIGN KEY (subject_code) REFERENCES Subjects(subject_code),
    CONSTRAINT fk_classes_professor FOREIGN KEY (professor_id) REFERENCES Professors(professor_id)
);

-- =========================
-- 5. ENROLLMENTS
-- =========================
CREATE TABLE Enrollments (
    enrollment_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id VARCHAR2(20),
    class_id NUMBER,
    CONSTRAINT fk_enroll_student FOREIGN KEY (student_id) REFERENCES Students(student_id),
    CONSTRAINT fk_enroll_class FOREIGN KEY (class_id) REFERENCES Classes(class_id)
);

-- =========================
-- 6. EVALUATIONS
-- =========================
CREATE TABLE Evaluations (
    evaluation_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrollment_id NUMBER,
    date_submitted TIMESTAMP,
    CONSTRAINT fk_eval_enrollment FOREIGN KEY (enrollment_id) REFERENCES Enrollments(enrollment_id)
);

-- =========================
-- 7. FORMS
-- =========================
CREATE TABLE Forms (
    form_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_name VARCHAR2(255),
    is_remarks NUMBER(1)
);

-- =========================
-- 8. CATEGORIES
-- =========================
CREATE TABLE Categories (
    category_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_id NUMBER,
    category_name VARCHAR2(255),
    CONSTRAINT fk_categories_form FOREIGN KEY (form_id) REFERENCES Forms(form_id)
);

-- =========================
-- 9. QUESTIONS
-- =========================
CREATE TABLE Questions (
    question_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id NUMBER,
    question_text VARCHAR2(500),
    CONSTRAINT fk_questions_category FOREIGN KEY (category_id) REFERENCES Categories(category_id)
);

-- =========================
-- 10. RESPONSES
-- =========================
CREATE TABLE Responses (
    response_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_id NUMBER,
    question_id NUMBER,
    rating NUMBER(1),
    CONSTRAINT fk_response_eval FOREIGN KEY (evaluation_id) REFERENCES Evaluations(evaluation_id),
    CONSTRAINT fk_response_question FOREIGN KEY (question_id) REFERENCES Questions(question_id)
);

-- =========================
-- 11. REMARKS
-- =========================
CREATE TABLE Remarks (
    remark_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_id NUMBER,
    remarks_text CLOB,
    CONSTRAINT fk_remarks_eval FOREIGN KEY (evaluation_id) REFERENCES Evaluations(evaluation_id)
);

