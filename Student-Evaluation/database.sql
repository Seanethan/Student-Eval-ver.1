    e.evaluation_id,
    s.student_id,
    p.name AS professor,
    c.subject_code,
    e.date_submitted,
    e.total_score,
    r.remarks_text
FROM system.Evaluations e
JOIN system.Students s ON e.student_id = s.student_id
JOIN system.Professors p ON e.professor_id = p.professor_id
JOIN system.Classes c ON e.class_id = c.class_id
LEFT JOIN system.Remarks r ON e.evaluation_id = r.evaluation_id;

