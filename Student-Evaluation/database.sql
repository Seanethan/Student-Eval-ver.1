-- TRIGGER 1: Auto-create evaluation when enrollment is added
CREATE OR REPLACE TRIGGER trg_enrollment_creates_evaluation
AFTER INSERT ON Enrollments
FOR EACH ROW
BEGIN
    INSERT INTO Evaluations (enrollment_id, status)
    VALUES (:NEW.enrollment_id, 'PENDING');
    
    -- Log the action
    INSERT INTO AuditLog (table_name, action_type, record_id, changed_by, change_date)
    VALUES ('Enrollments', 'INSERT', :NEW.enrollment_id, USER, SYSTIMESTAMP);
END;
/

-- TRIGGER 2: Validate rating is between 1 and 5
CREATE OR REPLACE TRIGGER trg_validate_rating
BEFORE INSERT OR UPDATE ON Responses
FOR EACH ROW
BEGIN
    IF :NEW.rating < 1 OR :NEW.rating > 5 THEN
        RAISE_APPLICATION_ERROR(-20002, 'Rating must be between 1 and 5.');
    END IF;
END;
/

-- TRIGGER 3: Cascade delete responses and remarks when evaluation is deleted
CREATE OR REPLACE TRIGGER trg_cascade_delete_responses
BEFORE DELETE ON Evaluations
FOR EACH ROW
BEGIN
    -- Log before deleting
    INSERT INTO AuditLog (table_name, action_type, record_id, old_value, changed_by, change_date)
    VALUES ('Evaluations', 'DELETE', :OLD.evaluation_id, 'Evaluation ID: ' || :OLD.evaluation_id, USER, SYSTIMESTAMP);
    
    DELETE FROM Responses WHERE evaluation_id = :OLD.evaluation_id;
    DELETE FROM Remarks WHERE evaluation_id = :OLD.evaluation_id;
END;
/

-- TRIGGER 4: Prevent duplicate enrollment
CREATE OR REPLACE TRIGGER trg_prevent_duplicate_enrollment
BEFORE INSERT ON Enrollments
FOR EACH ROW
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
    FROM Enrollments
    WHERE student_id = :NEW.student_id
      AND class_id = :NEW.class_id
      AND status = 'ACTIVE';
    
    IF v_count > 0 THEN
        RAISE_APPLICATION_ERROR(-20007, 'Student is already actively enrolled in this class.');
    END IF;
END;
/

