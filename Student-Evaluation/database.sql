    v_old_value VARCHAR2(100);
    v_new_value VARCHAR2(100);
BEGIN
    IF :OLD.rating != :NEW.rating THEN
        v_old_value := 'Rating: ' || :OLD.rating;
        v_new_value := 'Rating: ' || :NEW.rating;
        
