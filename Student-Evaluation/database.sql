-- TRIGGER 11: NEW - Prevent enrollment if class is full
CREATE OR REPLACE TRIGGER trg_check_class_capacity
BEFORE INSERT ON Enrollments
FOR EACH ROW
DECLARE
    v_current_students NUMBER;
    v_max_students NUMBER;
BEGIN
    -- Get current enrollment count for this class
    SELECT COUNT(*) INTO v_current_students
    FROM Enrollments
    WHERE class_id = :NEW.class_id AND status = 'ACTIVE';
    
    -- Get max capacity for this class
    SELECT max_students INTO v_max_students
    FROM Classes
    WHERE class_id = :NEW.class_id;
    
    IF v_current_students >= v_max_students THEN
        RAISE_APPLICATION_ERROR(-20009, 'Class is already full. Maximum capacity: ' || v_max_students);
    END IF;
END;
/

