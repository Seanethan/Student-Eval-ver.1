-- PROCEDURE 3: Archive old evaluations
CREATE OR REPLACE PROCEDURE archive_old_evaluations(p_days_old NUMBER DEFAULT 365)
AS
    v_cutoff_date DATE := SYSDATE - p_days_old;
    v_count NUMBER := 0;
BEGIN
    BEGIN
        EXECUTE IMMEDIATE '
            CREATE TABLE Evaluations_Archive AS 
            SELECT * FROM Evaluations WHERE 1=0';
    EXCEPTION
        WHEN OTHERS THEN
            NULL;
    END;
    
    FOR eval_rec IN (
        SELECT evaluation_id 
        FROM Evaluations 
        WHERE date_submitted < v_cutoff_date
          AND status = 'SUBMITTED'
    ) LOOP
        INSERT INTO Evaluations_Archive 
        SELECT * FROM Evaluations 
        WHERE evaluation_id = eval_rec.evaluation_id;
        
        UPDATE Evaluations 
        SET status = 'ARCHIVED'
        WHERE evaluation_id = eval_rec.evaluation_id;
        
        v_count := v_count + 1;
    END LOOP;
    
    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Archived ' || v_count || ' evaluations older than ' || p_days_old || ' days');
END;
/

-- PROCEDURE 4: NEW - Batch enrollment for student
CREATE OR REPLACE PROCEDURE enroll_student_in_multiple_classes(
    p_student_id VARCHAR2,
    p_class_ids VARCHAR2  -- Comma-separated class IDs
)
AS
    v_class_id NUMBER;
    v_start_pos NUMBER := 1;
    v_end_pos NUMBER;
    v_class_list VARCHAR2(1000) := p_class_ids;
BEGIN
    LOOP
        v_end_pos := INSTR(v_class_list, ',', v_start_pos);
        IF v_end_pos = 0 THEN
            v_class_id := TO_NUMBER(TRIM(SUBSTR(v_class_list, v_start_pos)));
            INSERT INTO Enrollments (student_id, class_id, status)
            VALUES (p_student_id, v_class_id, 'ACTIVE');
            EXIT;
        ELSE
            v_class_id := TO_NUMBER(TRIM(SUBSTR(v_class_list, v_start_pos, v_end_pos - v_start_pos)));
            INSERT INTO Enrollments (student_id, class_id, status)
            VALUES (p_student_id, v_class_id, 'ACTIVE');
            v_start_pos := v_end_pos + 1;
        END IF;
    END LOOP;
    
    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Student ' || p_student_id || ' enrolled successfully');
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20013, 'Error enrolling student: ' || SQLERRM);
END;
/

